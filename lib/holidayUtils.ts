/**
 * 특정 날짜가 주말(토/일) 또는 법정공휴일/대체공휴일인지 검증
 */
export function isWeekendOrHoliday(date: Date): boolean {
  const day = date.getDay();
  // 토요일(6) 또는 일요일(0)인 경우
  if (day === 0 || day === 6) return true;

  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, "0");
  const d = String(date.getDate()).padStart(2, "0");
  const std = `${y}-${m}-${d}`;
  const mmDd = `${m}-${d}`;

  // 1. 양력 고정 공휴일 체크
  if (FIXED_SOLAR_HOLIDAYS[mmDd]) return true;

  // 2. 음력 명절 및 대체공휴일 체크
  if (KOREAN_NATIONAL_HOLIDAYS[std]) return true;

  return false;
}
